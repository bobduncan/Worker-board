// B297: the backlog as a view of the work store (spec 2026-10-17, section 3). Once the store is the truth (the
// cutover, tools/migrate-backlog.mjs --cutover), the server writes backlog.md from the store after every change, in
// today's form, so whatever still reads the file reads what the store says. Its first line says it is generated;
// nobody edits it. What a step's line cannot say stands in one "[store]" line under it (adapter.mjs, `storeLine`),
// so the view migrates back to the same items.

import { createHash, randomBytes } from 'node:crypto'
import { copyFile, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { basename, dirname, join } from 'node:path'

import { backlogText } from './adapter.mjs'
import { GENERATED, stamp } from './migrate.mjs'

export { GENERATED }

const files = { readFile, writeFile, rename, rm, copyFile, mkdir }
const hashOf = text => createHash('sha1').update(text).digest('hex')
/** Where the store keeps the hash of the view it last wrote, and the last hand-edited view it kept. */
export const VIEW_FILE = 'view.json'

/** The view's first line: where it comes from, and that nothing in it is to be edited. */
export const generatedLine = dir => `<!-- generated by the worker board from ${String(dir).replace(/-->/g, '- ->')}; edit nothing here -->`

/** The store (`{ dir, items, activities, preamble }`, as readStore gives it) as backlog.md's text. */
export function backlogView({ dir, items, activities, preamble = [] }) {
  return `${generatedLine(dir)}\n${backlogText(items, activities, preamble)}`
}

/**
 * Writes the view to `file`: beside it, then put in place in one move, so a reader never finds half a file. Only
 * when its text changed. Review 4: the store keeps the hash of the view it wrote last (`<work>/view.json`); a file
 * that no longer has it was edited by hand, and is kept beside the view as `<name>.edited-<date>-<time>.md` before the
 * view is written, so no word is lost; `kept` names it, and the board says so on its top line.
 * `{ ok, changed, kept }` or `{ ok: false, why }`.
 */
export async function writeView(store, file, fs = files, { now = Date.now() } = {}) {
  const text = backlogView(store)
  const before = await fs.readFile(file, 'utf8').catch(() => null)
  const record = join(store.dir, VIEW_FILE)
  const last = await fs.readFile(record, 'utf8').then(JSON.parse, () => ({}))
  if (before === text) return { ok: true, changed: false, kept: null }
  let kept = null
  try {
    if (before !== null && typeof last.hash === 'string' && hashOf(before) !== last.hash) {
      kept = join(dirname(file), `${basename(file).replace(/\.md$/i, '')}.edited-${stamp(now).replace(' ', '-').replace(':', '')}.md`)
      await fs.copyFile(file, kept)
    }
    const beside = `${file}.${process.pid}.${randomBytes(4).toString('hex')}.tmp`
    await fs.writeFile(beside, text, { flag: 'wx' }).then(() => fs.rename(beside, file), async error => {
      await fs.rm(beside, { force: true }).catch(() => {})
      throw error
    })
    await fs.mkdir(store.dir, { recursive: true })
    await fs.writeFile(record, `${JSON.stringify({ hash: hashOf(text), kept: kept === null ? last.kept ?? null : { file: kept, at: stamp(now) } })}\n`)
    return { ok: true, changed: true, kept }
  } catch (error) {
    return { ok: false, why: `The view could not be written (${error.code ?? error.message}).` }
  }
}
