// B297: the backlog as a view of the work store (spec 2026-10-17, section 3). Once the store is the truth (the
// cutover, tools/migrate-backlog.mjs --cutover), the server writes backlog.md from the store after every change, in
// today's form, so whatever still reads the file reads what the store says. Its first line says it is generated;
// nobody edits it. What a step's line cannot say stands in one "[store]" line under it (adapter.mjs, `storeLine`),
// so the view migrates back to the same items.

import { randomBytes } from 'node:crypto'
import { readFile, rename, rm, writeFile } from 'node:fs/promises'

import { backlogText } from './adapter.mjs'
import { GENERATED } from './migrate.mjs'

export { GENERATED }

const files = { readFile, writeFile, rename, rm }

/** The view's first line: where it comes from, and that nothing in it is to be edited. */
export const generatedLine = dir => `<!-- generated by the worker board from ${String(dir).replace(/-->/g, '- ->')}; edit nothing here -->`

/** The store (`{ dir, items, activities, preamble }`, as readStore gives it) as backlog.md's text. */
export function backlogView({ dir, items, activities, preamble = [] }) {
  return `${generatedLine(dir)}\n${backlogText(items, activities, preamble)}`
}

/**
 * Writes the view to `file`: beside it, then put in place in one move, so a reader never finds half a file. Only
 * when its text changed. `{ ok, changed }` or `{ ok: false, why }`.
 */
export async function writeView(store, file, fs = files) {
  const text = backlogView(store)
  const before = await fs.readFile(file, 'utf8').catch(() => null)
  if (before === text) return { ok: true, changed: false }
  const beside = `${file}.${process.pid}.${randomBytes(4).toString('hex')}.tmp`
  try {
    await fs.writeFile(beside, text, { flag: 'wx' })
    await fs.rename(beside, file)
    return { ok: true, changed: true }
  } catch (error) {
    await fs.rm(beside, { force: true }).catch(() => {})
    return { ok: false, why: `The view could not be written (${error.code ?? error.message}).` }
  }
}
