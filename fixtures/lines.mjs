// Builders for made-up transcript lines, in the shape the Claude app writes them. The tests and the demo use them;
// nothing here comes from a real chat.

export const line = entry => JSON.stringify(entry)

const iso = at => new Date(at).toISOString()

export const user = (at, content, extra = {}) =>
  line({ type: 'user', timestamp: iso(at), message: { role: 'user', content }, ...extra })

/** Something the person typed in the app. */
export const typed = (at, text) => user(at, text, { origin: { kind: 'human' } })

/** A tool's answer: a user entry that no person wrote. */
export const toolResult = at => user(at, [{ type: 'tool_result', tool_use_id: 'tool-1', content: 'ok' }])

/** A message from another chat, as the app stores it: a preamble, the tag, and the plain text in `origin.body`. */
export const fromChat = (at, title, body) =>
  user(at, `Another Claude session sent a message:\n<cross-session-message from="local_${title}">\n${body}\n</cross-session-message>`, {
    isMeta: true,
    origin: { kind: 'peer', from: 'uds:pipe', name: title, fromSession: `local_${title}`, body },
  })

/**
 * A message from another chat that arrives while a turn runs: the app keeps it with the turn, as a queued command,
 * not as a user entry. `name` is left out by the app when it passes the message on itself.
 */
export const midTurn = (at, session, body, name = null) => line({
  type: 'attachment',
  timestamp: iso(at),
  attachment: {
    type: 'queued_command',
    prompt: `<cross-session-message from="${session}"${name === null ? '' : ` name="${name}"`}>\n${body}\n</cross-session-message>`,
    commandMode: 'prompt',
    origin: name === null ? { kind: 'peer', from: session, hostInjected: true } : { kind: 'peer', from: 'uds:pipe', name, fromSession: session, body },
    isMeta: true,
  },
})

export const assistant = (at, stopReason, blocks) =>
  line({ type: 'assistant', timestamp: iso(at), message: { role: 'assistant', stop_reason: stopReason, content: blocks } })

export const text = value => ({ type: 'text', text: value })

export const tool = (name, input = {}) => ({ type: 'tool_use', id: 'tool-1', name, input })

/** The end of a turn: the answer the person reads. */
export const answer = (at, value) => assistant(at, 'end_turn', [text(value)])

/** One step of a running turn: a tool call with what it is for. */
export const step = (at, description, name = 'Bash') => assistant(at, 'tool_use', [tool(name, { description })])

/** The three entries a slash command such as /reload-plugins leaves behind. No turn starts with them. */
export const slashCommand = (at, name) => [
  user(at, '<local-command-caveat>Caveat: the messages below were generated by the user.</local-command-caveat>', { isMeta: true }),
  user(at, `<command-name>${name}</command-name>`),
  user(at, '<local-command-stdout>Done</local-command-stdout>'),
]
