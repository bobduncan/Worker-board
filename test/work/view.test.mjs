// B297: the backlog as a view of the store (spec 2026-10-17, section 3): backlog.md is written from it in today's form, marked as generated on its first line. What the line cannot say (a state such as
// taken or review, a goal) stands in one "[store]" line under the step, so the view migrates back to the same items.
// Made-up samples only.

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

import { parseBacklog } from '../../src/backlog.mjs'
import { storeAsBacklog } from '../../src/work/adapter.mjs'
import { valueOf } from '../../src/work/item.mjs'
import { migrateBacklog } from '../../src/work/migrate.mjs'
import { GENERATED, backlogView } from '../../src/work/view.mjs'

const TEXT = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'fixtures', 'backlog-small.md'), 'utf8')
const NOW = new Date(2026, 9, 17, 11, 5).getTime()
const RULES = { prefix: 'Team - ', names: ['Board', 'Support', 'Units', 'Levels / Environment'] }

/** What the view can carry of an item: its head without Since, its sections without History. */
const carried = item => ({
  head: Object.fromEntries([...item.head].filter(([key]) => key !== 'Since')),
  sections: Object.fromEntries([...item.sections].filter(([name]) => name !== 'History')),
})
const sameItems = (a, b) => {
  assert.deepEqual([...a.keys()], [...b.keys()])
  for (const [id, item] of a) assert.deepEqual(carried(b.get(id)), carried(item), id)
}

/** The fixture's store with a change: `change(items)` edits the items in place. */
function changed(change) {
  const store = migrateBacklog(TEXT, { now: NOW })
  change(store.items)
  return { dir: 'C:/somewhere/work', ...store }
}
const set = (item, key, value) => (value === null ? item.head.delete(key) : item.head.set(key, value))

test('the view starts with the generated line and reads as today\'s backlog', () => {
  const store = changed(() => {})
  const view = backlogView(store)
  assert.equal(view.split('\n')[0], '<!-- generated by the worker board from C:/somewhere/work; edit nothing here -->')
  assert.match(view.split('\n')[0], GENERATED)
  // Below its first line the view is the backlog it came from, line for line, blank lines aside.
  const lines = text => text.split('\n').map(line => line.replace(/\r$/, '')).filter(line => line.trim() !== '')
  assert.deepEqual(lines(view).slice(1), lines(TEXT))
  assert.deepEqual(parseBacklog(view, RULES), parseBacklog(TEXT, RULES))
})

test('backlogView(store) parses back to the same store (view → migrate → equal items)', () => {
  const store = changed(items => {
    set(items.get('B10'), 'State', 'taken')
    set(items.get('B11'), 'State', 'in progress')
    set(items.get('B17'), 'State', 'review')
    items.get('B17').sections.set('Context', [...items.get('B17').sections.get('Context'), '  Reported by Units on 2026-10-17 at 11:05: the shop is merged.'])
    set(items.get('B18'), 'State', 'dropped')
    set(items.get('B12'), 'Goal', 'G17')
    set(items.get('B12'), 'Blocked by', 'B13')
    set(items.get('B24'), 'Pictures', null)
    set(items.get('B15'), 'State', 'answered')
  })
  const back = migrateBacklog(backlogView(store), { now: NOW + 60_000 })
  sameItems(store.items, back.items)
  assert.deepEqual(back.activities, store.activities)
  assert.deepEqual(back.preamble, store.preamble)
  assert.equal(valueOf(back.items.get('B18'), 'State'), 'dropped')
})

test('a step of the store that the line cannot say carries one [store] line, and only then', () => {
  const plain = backlogView(changed(() => {}))
  assert.doesNotMatch(plain, /\[store\]/)
  const view = backlogView(changed(items => {
    set(items.get('B10'), 'State', 'taken')
    set(items.get('B10'), 'Goal', 'G17')
  }))
  const lines = view.split('\n')
  const at = lines.findIndex(line => line.startsWith('- [ ] B10 '))
  assert.equal(lines[at + 1], '  [store] State: taken · Goal: G17')
  // The board reads it as a line under the step, nothing more.
  const step = parseBacklog(view, RULES).activities[0].steps[0]
  assert.equal(step.notes[0], '[store] State: taken · Goal: G17')
})

test('a dropped step stands ticked on the view; a done one too', () => {
  const view = backlogView(changed(items => set(items.get('B18'), 'State', 'dropped')))
  assert.match(view, /^- \[x\] B18 See enemy plans \(later; not handed out\)$/m)
  const steps = storeAsBacklog(changed(items => set(items.get('B18'), 'State', 'dropped')).items, changed(() => {}).activities, RULES).activities[0].steps
  assert.equal(steps.find(step => step.id === 'B18').isDone, true)
})

test('review 4: a hand edit of the view is kept beside it before the view is written anew, and the board says so', async () => {
  const { mkdtemp, readFile, readdir, rm, writeFile } = await import('node:fs/promises')
  const { tmpdir } = await import('node:os')
  const { readStore } = await import('../../src/work/store.mjs')
  const { storeBacklog } = await import('../../src/work/read.mjs')
  const { writeView } = await import('../../src/work/view.mjs')
  const root = await mkdtemp(join(tmpdir(), 'work-view-'))
  try {
    const dir = join(root, 'work')
    const file = join(root, 'backlog.md')
    await writeFile(file, TEXT)
    const store = changed(() => {})
    // The first view (the cutover's) writes over the backlog it came from: that one is kept by the cutover itself.
    assert.deepEqual(await writeView({ ...store, dir }, file, undefined, { now: NOW }), { ok: true, changed: true, kept: null })
    assert.deepEqual(await readdir(root), ['backlog.md', 'work'])
    // Unchanged: nothing is kept, nothing written.
    assert.deepEqual(await writeView({ ...store, dir }, file, undefined, { now: NOW }), { ok: true, changed: false, kept: null })
    // A chat edits the view by hand; the next change keeps that file and writes the view.
    const edited = (await readFile(file, 'utf8')).replace('- [ ] B18', '- [x] B18')
    await writeFile(file, edited)
    const next = changed(items => items.get('B10').head.set('State', 'taken'))
    const done = await writeView({ ...next, dir }, file, undefined, { now: NOW + 60_000 })
    assert.equal(done.kept, join(root, 'backlog.edited-2026-10-17-1106.md'))
    assert.equal(await readFile(done.kept, 'utf8'), edited)
    assert.equal(await readFile(file, 'utf8'), backlogView({ ...next, dir }))
    // The board's top line names the kept file while it is there.
    const work = { ok: true, ...(await readStore(dir)) }
    assert.equal(work.viewKept, done.kept)
    const shown = storeBacklog({ ...work, dir, items: next.items, activities: next.activities, exists: true }, RULES)
    assert.equal(shown.store.kept, done.kept)
    await rm(done.kept)
    assert.equal((await readStore(dir)).viewKept, null)
  } finally {
    await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 })
  }
})
